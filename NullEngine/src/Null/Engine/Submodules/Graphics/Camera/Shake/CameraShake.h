namespace NULLENGINE
{
    struct CameraShake
    {
        float duration = 0.5f;
        float elapsed = 0.0f;

        float magnitude = 10.0f; // in pixels or units
        EasingType easing = EasingType::EaseOutQuad;

        glm::vec2 direction = glm::vec2(0.0f); // normalized direction
        float frequency = 20.0f; // how fast the shake jitters

        bool finished = false;

        glm::vec2 GetOffset(float deltaTime);

        bool IsFinished() const { return finished; }
    };

}